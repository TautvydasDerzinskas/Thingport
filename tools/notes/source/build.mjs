// Builds tool.js and tool.json from source/: the notes' data (notes.js), what the parts share (ui.js), the picture's
// part (preview.js) and the window (board.js), joined into one module, and the metadata with its icon, which is the
// picture's note button. Run from this folder's parent after changing any:
//   node source/build.mjs

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { NOTE_SVG } from "./ui.js";

const here = path.dirname(fileURLToPath(import.meta.url));
const tool = path.resolve(here, "..");
const read = (file) => fs.readFileSync(path.join(here, file), "utf8");

// The files import each other; in one module they're its own, so those lines go.
const local = /^import\s[^;]*\sfrom\s+"\.\/[\w-]+\.js";\n/gms;
const files = ["notes.js", "ui.js", "preview.js", "board.js"];
const parts = files.map((file) => {
  const text = read(file).replace(local, "");
  if (/^import\s/m.test(text)) throw new Error(`${file} imports something other than its neighbours`);
  return `// ---- ${file} ----\n\n${text.trim()}\n`;
});
const script = `// GENERATED by source/build.mjs from source/${files.join(", ")}: change those and build again.\n\n${parts.join("\n")}`;
fs.writeFileSync(path.join(tool, "tool.js"), script);

const base = JSON.parse(read("tool.base.json"));
const icon = `data:image/svg+xml;charset=utf-8,${encodeURIComponent(NOTE_SVG)}`;
fs.writeFileSync(path.join(tool, "tool.json"), `${JSON.stringify({ ...base, iconUrl: icon }, null, 2)}\n`);
console.log(`tool.js ${script.length} characters`);
