// Builds tool.js and tool.json from source/: the catalogue, the solver, the mounting, the print list, the 3MF
// writer, the drawing and the window, joined into one module, and the metadata with its icon and the models the
// tool brings. Run from this folder after changing any:
//   node source/build.mjs
// then `node source/test_planner.mjs` for the tests.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { collectionModels } from "./catalogue.js";

const here = path.dirname(fileURLToPath(import.meta.url));
const tool = path.resolve(here, "..");
const read = (file) => fs.readFileSync(path.join(here, file), "utf8");

const FILES = ["catalogue.js", "solver.js", "mounting.js", "printlist.js", "parts3mf.js", "plan2d.js", "ui.js"];

// The files import each other; joined into one module they're its own, so those lines go. An import that runs over
// several lines goes too, which is what the second pattern is for.
const local = /^import\s[\s\S]*?\sfrom\s+"\.\/[\w-]+\.js";\n/gm;
// What each file declares at its top level, to catch two of them claiming the same name: in one module that's a
// syntax error, and a confusing one, so the build says which files collided instead.
const DECLARES = /^(?:export\s+)?(?:async\s+)?(?:function|class|const|let|var)\s+([A-Za-z_$][\w$]*)/gm;

const seen = new Map();
const parts = FILES.map((file) => {
  const text = read(file).replace(local, "");
  if (/^import\s/m.test(text)) throw new Error(`${file} imports something other than its neighbours`);
  for (const [, name] of text.matchAll(DECLARES)) {
    if (seen.has(name)) throw new Error(`${file} and ${seen.get(name)} both declare \`${name}\`: rename one`);
    seen.set(name, file);
  }
  return `// ---- ${file} ----\n\n${text.trim()}\n`;
});

const script = `// GENERATED by source/build.mjs from source/${FILES.join(", ")}: change those and build again.\n\n${parts.join("\n")}`;
fs.writeFileSync(path.join(tool, "tool.js"), script);

// The models the tool brings are worked out from the same catalogue the window plans with, so the collection and
// the planner can never disagree about which profile holds which board.
const base = JSON.parse(read("tool.base.json"));
const icon = `data:image/svg+xml;charset=utf-8,${encodeURIComponent(read("icon.svg").trim())}`;
const manifest = {
  ...base,
  iconUrl: icon,
  collection: { name: "Skadis models", models: collectionModels() },
};
fs.writeFileSync(path.join(tool, "tool.json"), `${JSON.stringify(manifest, null, 2)}\n`);
console.log(`tool.js ${script.length} characters, ${manifest.collection.models.length} models`);
