// Thingport installs these two files together. Spread the image data across them to keep both within their limits.
import { readFileSync, writeFileSync } from "node:fs";
import { issues } from "./troubleshooting.js";

const localImport = /^import\s[^;]*\sfrom\s+"\.\/[\w-]+\.js";\n/gms;
const read = (file) => readFileSync(new URL(file, import.meta.url), "utf8");
const markup = read("window.html");
const scriptImages = {};
const markupImages = [];
let markupLength = markup.length;
for (const { id, imageAlt } of issues) {
  if (!imageAlt) continue;
  const bytes = readFileSync(new URL(`images/${id}.webp`, import.meta.url));
  const src = `data:image/webp;base64,${bytes.toString("base64")}`;
  const tag = `    <img\n      data-case="${id}"\n      src="${src}"\n    />`;
  // The HTML allowance is 200,000 characters. Reserve room for the template wrapper and future markup.
  if (markupLength + tag.length + 1 <= 195_000) {
    markupImages.push(tag);
    markupLength += tag.length + 1;
  } else scriptImages[id] = src;
}

const files = [
  "references.js",
  "troubleshooting.js",
  "history.js",
  "printers.js",
  "settings.js",
  "articles.js",
  "quiz.js",
  "ui.js",
  "diagrams.js",
  "exam.js",
  "window.js",
];
const parts = files.map((file) => {
  const source = read(file).replace(localImport, "");
  if (/^import\s/m.test(source)) throw new Error(`${file} imports something other than local source`);
  return `// ---- ${file} ----\n\n${source.trim()}\n`;
});
const script = parts.join("\n").replace("/* build:images */ {}", JSON.stringify(scriptImages, null, 2));
const html =
  "<!-- GENERATED by source/build.mjs from source/window.html and source/images/. -->\n" +
  markup.replace(
    "  <!-- build:images -->",
    ["  <template data-wiki-images>", ...markupImages, "  </template>"].join("\n"),
  );
writeFileSync(
  new URL("../tool.js", import.meta.url),
  `// GENERATED by source/build.mjs from source/${files.join(", ")} and source/images/.\n\n${script}`,
);
writeFileSync(new URL("../tool.html", import.meta.url), html);
console.log(`3D Printing Wiki script: ${script.length} characters, HTML: ${html.length} characters`);
