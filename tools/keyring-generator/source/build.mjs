// Builds tool.js and tool.json from source/: the curve flattening, the text and colour rules, the 2D geometry,
// the edge finishing, the magnets, the preview normals, the engine, the file writers, the viewer and the
// window, joined into one module. The words aren't here: they live in locales/, which Thingport reads itself.
// Run from the tool's folder after changing any:
//   node source/build.mjs
// then `node source/test_keyring.mjs` for the tests.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const tool = path.resolve(here, "..");
const read = (file) => fs.readFileSync(path.join(here, file), "utf8");

const FILES = [
  "curves.js",
  "text.js",
  "colours.js",
  "magnets.js",
  "geometry2d.js",
  "finishing.js",
  "meshNormals.js",
  "engine.js",
  "files.js",
  "viewer.js",
  "ui.js",
];

// The files import each other; joined into one module they're its own, so those lines go.
const local = /^import\s[\s\S]*?\sfrom\s+"\.\/[\w-]+\.js";\n/gm;
// What each declares at its top level, so two files can't quietly claim the same name.
const DECLARES = /^(?:export\s+)?(?:async\s+)?(?:function|class|const|let|var)\s+([A-Za-z_$][\w$]*)/gm;

const seen = new Map();
const parts = FILES.map((file) => {
  const text = read(file).replace(local, "");
  if (/^import\s/m.test(text)) throw new Error(`${file} imports something other than its neighbours`);
  for (const [, name] of text.matchAll(DECLARES)) {
    if (seen.has(name)) throw new Error(`${file} and ${seen.get(name)} both declare \`${name}\`: rename one`);
    seen.set(name, file);
  }
  return `// ---- ${file} ----\n\n${text.trim()}\n`;
});

const script = `// GENERATED by source/build.mjs from source/${FILES.join(", ")}: change those and build again.\n\n${parts.join("\n")}`;
fs.writeFileSync(path.join(tool, "tool.js"), script);

const base = JSON.parse(read("tool.base.json"));
const icon = `data:image/svg+xml;charset=utf-8,${encodeURIComponent(read("icon.svg").trim())}`;
fs.writeFileSync(path.join(tool, "tool.json"), `${JSON.stringify({ ...base, iconUrl: icon }, null, 2)}\n`);
console.log(`tool.js ${script.length} characters`);
