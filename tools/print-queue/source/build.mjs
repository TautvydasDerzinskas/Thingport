// Builds tool.js and tool.json from source/: the queue itself (queue.js) and the window (ui.js), joined into
// one module, and the metadata with its icon and symbols. Run from this folder after changing any:
//   node source/build.mjs

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const tool = path.resolve(here, "..");
const read = (file) => fs.readFileSync(path.join(here, file), "utf8");

// The files import each other; in one module they're its own, so those lines go.
const local = /^import\s[^;]*\sfrom\s+"\.\/[\w-]+\.js";\n/gms;
const files = ["queue.js", "ui.js"];
const parts = files.map((file) => {
  const text = read(file).replace(local, "");
  if (/^import\s/m.test(text)) throw new Error(`${file} imports something other than its neighbours`);
  return `// ---- ${file} ----\n\n${text.trim()}\n`;
});
const script = `// GENERATED by source/build.mjs from source/${files.join(", ")}: change those and build again.\n\n${parts.join("\n")}`;
fs.writeFileSync(path.join(tool, "tool.js"), script);

const base = JSON.parse(read("tool.base.json"));
const svgData = (file) => `data:image/svg+xml;charset=utf-8,${encodeURIComponent(read(file).trim())}`;
// The symbols are named by file in tool.base.json and written into the metadata, as the icon is.
const symbol = (file) => (file ? svgData(file) : undefined);
const manifest = {
  ...base,
  iconUrl: svgData("icon.svg"),
  symbol: symbol(base.symbol),
  commands: base.commands?.map((command) => ({ ...command, symbol: symbol(command.symbol) })),
};
fs.writeFileSync(path.join(tool, "tool.json"), `${JSON.stringify(manifest, null, 2)}\n`);
console.log(`tool.js ${script.length} characters`);
