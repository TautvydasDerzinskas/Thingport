// Builds tool.js and tool.json from source/: the 3MF Sanitizer's conversion (sanitizer.js, kept as it is so its tests
// still run), the ZIP reader and writer, the preview and the window (ui.js), and the metadata with its icon. Run from
// this folder after changing any:
//   node source/build.mjs
// then `node source/test_sanitizer.mjs` for the sanitizer's tests.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const tool = path.resolve(here, "..");
const read = (file) => fs.readFileSync(path.join(here, file), "utf8");

// sanitizer.js sets globalThis.ThreeMFSanitizer, or module.exports; in the tool it's a module's own.
let sanitizer = read("sanitizer.js");
const wrapper = `(function (root, factory) {
    if (typeof module === "object" && module.exports) {
        module.exports = factory();
    } else {
        root.ThreeMFSanitizer = factory();
    }
})(typeof globalThis !== "undefined" ? globalThis : this, function () {`;
if (!sanitizer.includes(wrapper)) throw new Error("sanitizer.js no longer opens as it did");
sanitizer = sanitizer.replace(
  wrapper,
  "const ThreeMFSanitizer = (function (factory) {\n    return factory();\n})(function () {",
);

// The other files import each other; in one module they're its own, so those lines go.
const local = /^import\s[^;]*\sfrom\s+"\.\/[\w-]+\.js";\n/gm;
const own = (file) => {
  const text = read(file).replace(local, "");
  if (/^import\s/m.test(text)) throw new Error(`${file} imports something other than its neighbours`);
  return `// ---- ${file} ----\n\n${text.trim()}\n`;
};
const script = [
  "// GENERATED by source/build.mjs from source/zip.js, sanitizer.js, preview.js and ui.js: change those and build again.\n",
  own("zip.js"),
  `// ---- sanitizer.js ----\n\n${sanitizer.trim()}\nexport { ThreeMFSanitizer };\n`,
  own("preview.js"),
  own("ui.js"),
].join("\n");
fs.writeFileSync(path.join(tool, "tool.js"), script);

const base = JSON.parse(read("tool.base.json"));
const icon = `data:image/svg+xml;charset=utf-8,${encodeURIComponent(read("icon.svg").trim())}`;
fs.writeFileSync(path.join(tool, "tool.json"), `${JSON.stringify({ ...base, iconUrl: icon }, null, 2)}\n`);
console.log(`tool.js ${script.length} characters`);
