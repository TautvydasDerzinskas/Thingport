// Builds tool.js and tool.json from source/: the planner's core (a port of the original Multiboard Planner, kept as it
// is so its tests still run), its part data, its window (ui.js) and icon. Run from this folder after changing any:
//   node source/build.mjs
// then `node source/test_core.mjs` for the original planner's tests.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const tool = path.resolve(here, "..");
const read = (file) => fs.readFileSync(path.join(here, file), "utf8");

// core.js sets globalThis.PlannerCore; in the tool it's a module's own.
let core = read("core.js");
const swaps = [
  ["(function (root) {", "const PlannerCore = (function () {"],
  ["root.PlannerCore = {", "return {"],
  ["})(typeof window !== 'undefined' ? window : globalThis);", "})();"],
];
for (const [from, to] of swaps) {
  if (!core.includes(from)) throw new Error(`core.js no longer has ${JSON.stringify(from)}`);
  core = core.replace(from, to);
}

const data = {
  partLinks: read("data/PartLinks.csv"),
  snaps: read("data/SnapsList.csv"),
  tileNames: read("data/TileNames1.txt"),
};

const script = `// GENERATED by source/build.mjs from source/core.js, source/data/ and source/ui.js: change those and build again.

const PLANNER_DATA = ${JSON.stringify(data)};

${core}
export { PlannerCore };

${read("ui.js")}`;
fs.writeFileSync(path.join(tool, "tool.js"), script);

// The models it brings: each part the planner links to, once, fetched from Thangs when an admin installs the tool.
const { PlannerCore, modelKey } = await import(pathToFileURL(path.join(tool, "tool.js")).href);
const { parseCsv } = PlannerCore;
const tileNames = new Map(
  parseCsv(data.tileNames)
    .slice(1)
    .filter((row) => row.length >= 2)
    .map((row) => [row[0], row[1]]),
);
const models = new Map();
const add = (link, name, tags) => {
  const key = modelKey(link);
  if (!key || models.has(key)) return;
  const source = `https://thangs.com/m/${key.slice("thangs-".length)}`;
  models.set(key, { key, name: name.slice(0, 200), tags: ["multiboard", ...tags], source });
};
for (const [size, type, link] of parseCsv(data.partLinks).slice(1)) {
  if (!link) continue;
  add(link, `${size} ${tileNames.get(type) ?? type} Tile`, ["tile"]);
}
for (const row of parseCsv(data.snaps)) {
  if (row.length < 5) continue;
  // As the planner names it: its line breaks are written "\\n" in the file, and other backslashes dropped.
  add(row[4], row[1].replace(/\\n/g, " ").replace(/\\/g, "").replace(/\s+/g, " ").trim(), ["mount"]);
}

const base = JSON.parse(read("tool.base.json"));
const icon = `data:image/svg+xml;charset=utf-8,${encodeURIComponent(read("icon.svg").trim())}`;
const manifest = {
  ...base,
  iconUrl: icon,
  collection: { ...base.collection, models: [...models.values()] },
};
fs.writeFileSync(path.join(tool, "tool.json"), `${JSON.stringify(manifest, null, 2)}\n`);
console.log(`tool.js ${script.length} characters, tool.json with ${models.size} models`);
