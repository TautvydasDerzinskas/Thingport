// Builds tool.js and tool.json from source/: the planner's core (a port of the original Multiboard Planner, kept as it
// is so its tests still run), its part data, its window (ui.js) and icon. Run from this folder after changing any:
//   node source/build.mjs
// then `node source/test_core.mjs` for the original planner's tests.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const tool = path.resolve(here, "..");
const read = (file) => fs.readFileSync(path.join(here, file), "utf8");

// core.js sets globalThis.PlannerCore; in the tool it's a module's own.
let core = read("core.js");
const swaps = [
  ["(function (root) {", "const PlannerCore = (function () {"],
  ["root.PlannerCore = {", "return {"],
  ["})(typeof window !== 'undefined' ? window : globalThis);", "})();"],
];
for (const [from, to] of swaps) {
  if (!core.includes(from)) throw new Error(`core.js no longer has ${JSON.stringify(from)}`);
  core = core.replace(from, to);
}

// One file for all the part data: which tile links to which model, what each tile type is called, and the
// mounting snaps. It was three CSVs, which only the original planner's loader could read.
const data = JSON.parse(read("data/parts.json"));

// plate.scad travels with the tool rather than being fetched: a plate is drawn in the tab, from text the
// tool already has, and nothing leaves it.
const script = `// GENERATED by source/build.mjs from source/core.js, source/data/, source/stl.js, source/plates.js, source/plate.scad
// and source/ui.js: change those and build again.

const PLANNER_DATA = ${JSON.stringify(data)};

export const PLATE_SCAD = ${JSON.stringify(read("plate.scad"))};

${core}
export { PlannerCore };

${read("stl.js")}

${read("plates.js")}

${read("ui.js")}`;
fs.writeFileSync(path.join(tool, "tool.js"), script);

// The models it brings. The plates are not among them: the planner draws those from plate.scad when a wall is
// saved, so the 208 that used to be fetched from Thangs and kept for every instance are gone, and with them the
// twelve gigabytes they took and the Thangs account an admin needed to install the tool.
//
// The joints cannot be drawn -- they are snaps and clips, not a pattern -- so the tool carries their files, which
// Multiboard have agreed to (see the README).
const { modelKey } = await import(pathToFileURL(path.join(tool, "tool.js")).href);
const models = new Map();
for (const snap of data.snaps) {
  const key = modelKey(snap.link);
  if (!key || models.has(key)) continue;
  const dir = path.join(tool, "models", key);
  if (!fs.existsSync(dir)) throw new Error(`${key} has no files in models/: copy them in before building`);
  // In plate order, which for a snap of several is its variants: Loose, Permanent, Standard, Tight.
  const files = fs
    .readdirSync(dir)
    .filter((file) => file.toLowerCase().endsWith(".stl"))
    .sort()
    .map((file) => `models/${key}/${file}`);
  if (!files.length) throw new Error(`${key} has no STL in models/`);
  if (files.length > 20) throw new Error(`${key} has ${files.length} files, and a model may have 20`);
  // As the planner names it: its line breaks are written "\\n" in the data, and other backslashes dropped.
  const name = snap.name.replace(/\\n/g, " ").replace(/\\/g, "").replace(/\s+/g, " ").trim();
  models.set(key, { key, name: name.slice(0, 200), tags: ["multiboard", "mount"], files });
}

const base = JSON.parse(read("tool.base.json"));
const icon = `data:image/svg+xml;charset=utf-8,${encodeURIComponent(read("icon.svg").trim())}`;
const manifest = {
  ...base,
  iconUrl: icon,
  collection: { ...base.collection, models: [...models.values()] },
};
fs.writeFileSync(path.join(tool, "tool.json"), `${JSON.stringify(manifest, null, 2)}\n`);
console.log(
  `tool.js ${script.length} characters (plate.scad ${read("plate.scad").length} of them), tool.json with ${models.size} models`,
);
