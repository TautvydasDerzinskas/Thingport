// Reads what a slicer exported, where the print time and the weight are already worked out and don't have to be
// guessed at. Every slicer writes them into the G-code as comments, each in its own wording, so there is a pattern
// here per slicer; a sliced 3MF from Bambu Studio or Orca carries them as a small XML file instead, one entry a plate.
//
// A file can be hundreds of megabytes of toolpath with the figures in the first and last few lines, so only the ends
// are read.

import { readZip } from "./zip.js";

/** A sliced file that can't be read, with a message written for the person who dropped it. */
export class SlicerError extends Error {}

const ENDS = 1024 * 1024;
const TEXT = new TextDecoder();
const SLICED = [".gcode", ".gco", ".g", ".bgcode", ".gcode.3mf"];

const PLA_DENSITY = 1.24;
const FILAMENT_DIAMETER = 1.75;

export const isSlicedName = (name) => {
  const lower = String(name ?? "").toLowerCase();
  return SLICED.some((extension) => lower.endsWith(extension));
};

const number = (text) => {
  if (text == null) return null;
  const value = parseFloat(text);
  return Number.isFinite(value) ? value : null;
};
const list = (text) =>
  (text ?? "")
    .split(/[,;]/)
    .map((part) => part.trim())
    .filter(Boolean);
const numbers = (text) => list(text).map(parseFloat).filter(Number.isFinite);
const total = (values) => values.reduce((sum, value) => sum + value, 0);
const grab = (text, pattern) => text.match(pattern)?.[1]?.trim() ?? null;

/** "1d 2h 3m 4s", "1h 56m 9s" or "13m 53s" in seconds. */
export function parseDuration(text) {
  if (!text) return null;
  const units = { d: 86400, h: 3600, m: 60, s: 1 };
  let seconds = 0;
  let found = false;
  for (const [, value, unit] of text.matchAll(/(\d+(?:\.\d+)?)\s*([dhms])(?![a-z])/gi)) {
    seconds += parseFloat(value) * units[unit.toLowerCase()];
    found = true;
  }
  return found ? seconds : null;
}

/** The "filament used [g] = 9.36, 9.63" line, one number a filament, skipping the "total" line of the same wording. */
function perFilament(text, unit) {
  for (const match of text.matchAll(new RegExp(`(total )?filament used \\[${unit}\\]\\s*=\\s*([^\\n\\r]+)`, "gi"))) {
    if (!match[1]) return numbers(match[2]);
  }
  return [];
}

/** Which slicer wrote it, to show beside the figures. */
function whichSlicer(text) {
  const generated = text.match(/generated by (\S+) (\S+) on /i); // PrusaSlicer, Orca
  if (generated) return `${generated[1]} ${generated[2]}`;
  const bambu = grab(text, /;\s*BambuStudio\S*\s+([\d.]+)/);
  if (bambu) return `Bambu Studio ${bambu}`;
  const cura = grab(text, /Cura_SteamEngine\s+([\d.]+)/);
  if (cura) return `Cura ${cura}`;
  return grab(text, /Producer=([^\n\r]+)/); // PrusaSlicer's binary G-code
}

/**
 * One plate from G-code: `{ seconds, totalGrams, purgeGrams, filaments, estimated }`, or null when the text holds
 * neither a time nor a weight. `estimated` means the weight was worked out from a length or a volume here, because
 * the profile that sliced it had no density in it.
 */
export function parseGcode(text) {
  let seconds =
    // Bambu Studio and Orca: "; total estimated time: 1h 56m 9s"
    parseDuration(grab(text, /total estimated time:\s*([^;\n\r]+)/i)) ??
    // PrusaSlicer and Orca, the binary .bgcode too: "; estimated printing time (normal mode) = 1h 14m 3s"
    parseDuration(grab(text, /estimated printing time \(normal mode\)\s*=\s*([^\n\r]+)/i));
  if (seconds == null) {
    // Cura writes seconds, and ";PRINT.TIME:" on an Ultimaker. A file with several takes the longest.
    const cura = [...text.matchAll(/^;(?:PRINT\.)?TIME:(\d+(?:\.\d+)?)/gm)].map((match) => parseFloat(match[1]));
    if (cura.length) seconds = Math.max(...cura);
  }

  const types = list(grab(text, /(?:^|\n)[;\s]*filament_type\s*[=:]\s*([^\n\r]+)/));
  const colours = list(grab(text, /(?:^|\n)[;\s]*filament_colou?r\s*[=:]\s*([^\n\r]+)/));
  const densities = numbers(grab(text, /filament_density\s*[=:]\s*([^\n\r]+)/i));
  const densityOf = (index) => densities[index] || densities[0] || PLA_DENSITY;

  let estimated = false;
  // PrusaSlicer and Orca give the grams outright, one a filament.
  let grams = perFilament(text, "g");
  // Cura, when the printer's profile writes it: ";Filament weight = [12.3, 4.5]"
  if (!total(grams)) grams = numbers(grab(text, /;Filament weight\s*=\s*\[([^\]]+)\]/i));
  // Only cubic centimetres, when the profile's density was left at zero.
  if (!total(grams)) {
    const cm3 = perFilament(text, "cm3");
    if (total(cm3)) {
      grams = cm3.map((volume, index) => volume * densityOf(index));
      estimated = densities.length === 0;
    }
  }
  // Cura: ";Filament used: 1.49416m, 0.5m", metres of 1.75 mm filament.
  if (!total(grams)) {
    const metres = numbers(grab(text, /^;Filament used:\s*([^\n\r]+)/m)?.replace(/m/g, ""));
    if (total(metres)) {
      const area = Math.PI * (FILAMENT_DIAMETER / 2) ** 2;
      grams = metres.map((length, index) => ((length * 1000 * area) / 1000) * densityOf(index));
      estimated = true;
    }
  }

  const totalGrams =
    number(grab(text, /total filament used \[g\]\s*=\s*([\d.]+)/i)) ||
    number(grab(text, /total filament weight \[g\]\s*:\s*([\d.]+)/i)) ||
    (total(grams) > 0 ? total(grams) : null);

  // PrusaSlicer says what went to the wipe tower. Zero means none; nothing at all means it didn't say, and the purge
  // is already inside the total.
  const purgeGrams = number(grab(text, /total filament used for wipe tower \[g\]\s*=\s*([\d.]+)/i));

  if (seconds == null && totalGrams == null) return null;

  const count = Math.max(grams.length, types.length > 1 ? types.length : 0);
  const filaments = Array.from({ length: count }, (_, index) => ({
    type: types[index] || types[0] || "",
    colour: colours[index] || "",
    grams: grams[index] ?? (count === 1 ? (totalGrams ?? 0) : 0),
  })).filter((filament) => filament.grams > 0);

  return { seconds, totalGrams, purgeGrams, filaments, estimated };
}

/** The plates of a sliced 3MF, from Metadata/slice_info.config: one entry a plate, the time in seconds. */
export function parseSliceInfo(xml) {
  const plates = [];
  for (const [, body] of xml.matchAll(/<plate>([\s\S]*?)<\/plate>/g)) {
    const meta = {};
    for (const [, key, value] of body.matchAll(/<metadata\s+key="([^"]*)"\s+value="([^"]*)"/g)) meta[key] = value;
    const filaments = [...body.matchAll(/<filament\b([^>]*?)\/?>/g)]
      .map(([, attributes]) => {
        const a = Object.fromEntries([...attributes.matchAll(/([\w-]+)="([^"]*)"/g)].map(([, k, v]) => [k, v]));
        return { type: a.type || "", colour: a.color || "", grams: number(a.used_g) ?? 0 };
      })
      .filter((filament) => filament.grams > 0);
    // Orca leaves the weight empty when the profile has no density, and the filaments add up to the same thing.
    const weight = number(meta.weight);
    const summed = total(filaments.map((filament) => filament.grams));
    plates.push({
      index: parseInt(meta.index, 10) || plates.length + 1,
      seconds: number(meta.prediction) || null,
      totalGrams: weight > 0 ? weight : summed > 0 ? summed : null,
      purgeGrams: null,
      filaments,
      estimated: false,
    });
  }
  return plates;
}

/** The first and last megabyte of a big file, or all of a small one. */
async function ends(source) {
  if (typeof source.slice === "function" && typeof source.text === "function") {
    if (source.size <= ENDS * 2) return source.text();
    const head = await source.slice(0, ENDS).text();
    const tail = await source.slice(source.size - ENDS).text();
    return `${head}\n${tail}`;
  }
  const bytes = source instanceof Uint8Array ? source : new Uint8Array(source);
  if (bytes.length <= ENDS * 2) return TEXT.decode(bytes);
  return `${TEXT.decode(bytes.subarray(0, ENDS))}\n${TEXT.decode(bytes.subarray(bytes.length - ENDS))}`;
}

async function readSliced3mf(bytes) {
  const entries = await readZip(bytes);
  const info = entries.get("Metadata/slice_info.config");
  let plates = info ? parseSliceInfo(await info.text()) : [];
  let slicer = null;

  // No slice info, or a plate missing a figure: read that plate's own G-code, which is in the archive beside it.
  const incomplete = !plates.length || plates.some((plate) => plate.seconds == null || plate.totalGrams == null);
  if (incomplete) {
    const names = [...entries.keys()].filter((name) => /^Metadata\/plate_\d+\.gcode$/.test(name));
    const numberOf = (name) => parseInt(name.match(/plate_(\d+)/)[1], 10);
    const fromGcode = [];
    for (const name of names.sort((a, b) => numberOf(a) - numberOf(b))) {
      const text = await ends(await entries.get(name).bytes());
      const parsed = parseGcode(text);
      if (parsed) fromGcode.push({ index: numberOf(name), ...parsed });
      slicer = slicer ?? whichSlicer(text);
    }
    if (!plates.length) plates = fromGcode;
    else
      plates = plates.map((plate) => {
        const found = fromGcode.find((other) => other.index === plate.index);
        if (!found) return plate;
        return {
          ...plate,
          seconds: plate.seconds ?? found.seconds,
          totalGrams: plate.totalGrams ?? found.totalGrams,
          purgeGrams: plate.purgeGrams ?? found.purgeGrams,
          filaments: plate.filaments.length ? plate.filaments : found.filaments,
          estimated: plate.totalGrams == null ? found.estimated : plate.estimated,
        };
      });
  }

  if (!plates.length) return null;
  return { slicer: slicer ?? "Bambu Studio / Orca Slicer", plates };
}

/**
 * What a slicer exported: `{ slicer, plates }`, or null when the file turns out not to be sliced after all — a plain
 * 3MF project, which the caller then measures as a mesh instead.
 */
export async function readSliced(source, name) {
  const lower = String(name ?? "").toLowerCase();
  if (lower.endsWith(".3mf")) {
    const bytes = source instanceof Uint8Array ? source : new Uint8Array(await asBuffer(source));
    return readSliced3mf(bytes);
  }
  const text = await ends(source);
  const parsed = parseGcode(text);
  if (!parsed) {
    throw new SlicerError(
      "No print time or filament weight in this file. If it's the G-code your slicer exported, type the two figures in by hand.",
    );
  }
  return { slicer: whichSlicer(text), plates: [{ index: 1, ...parsed }] };
}

const asBuffer = (source) => (typeof source.arrayBuffer === "function" ? source.arrayBuffer() : source);

/**
 * The figures for the form: a plate's number, or "all" to add every plate up, and how many parts are on it, to get
 * one part's share.
 */
export function platesToValues(plates, choice, parts) {
  const chosen = choice === "all" ? plates : plates.filter((plate) => plate.index === choice);
  const each = Math.max(1, Math.floor(parts) || 1);
  const values = {};
  if (chosen.length && chosen.every((plate) => plate.seconds != null)) {
    values.hours = total(chosen.map((plate) => plate.seconds)) / 3600 / each;
  }
  if (chosen.length && chosen.every((plate) => plate.totalGrams != null)) {
    const weight = total(chosen.map((plate) => plate.totalGrams));
    // When the file doesn't break the purge out it's already inside the weight, so leaving purge at zero is what
    // keeps it from being counted twice.
    const purge = total(chosen.map((plate) => plate.purgeGrams ?? 0));
    values.grams = Math.max(0, weight - purge) / each;
    values.purgeGrams = purge / each;
  }
  return values;
}
