import fs from "node:fs";
import path from "node:path";
import JSZip from "jszip";
import sharp from "sharp";
import { stl, threeMf, zip } from "../providers/support";

// The files a case sends, made from their names: what a file holds only has to be enough for the way in to treat it
// as that kind of file, so a name says it all. A zip is written out from the entries it's given.

/** A case's files by path. A value of null is a file made from its name; an object is a zip of those entries. */
export type FileTree = { [path: string]: FileTree | null };

const STEP = fs.readFileSync(path.join(__dirname, "..", "fixtures", "box.step"));

/** A sliced 3MF, as a slicer exports one: the plate's G-code beside the mesh, its header saying what wrote it. */
async function slicedThreeMf(seed: string): Promise<Buffer> {
  const gcode = Buffer.from(`; generated by BambuStudio 01.10.00.00\n; ${seed}\n; filament used [g] = 3.20\nG28\n`);
  const model = await threeMf(seed);
  const archive = await JSZip.loadAsync(model);
  archive.file("Metadata/plate_1.gcode", gcode);
  return archive.generateAsync({ type: "nodebuffer" });
}

function picture(seed: string, format: "png" | "jpeg"): Promise<Buffer> {
  let hash = 0;
  for (const char of seed) hash = (hash * 31 + char.charCodeAt(0)) >>> 0;
  const background = { r: hash & 255, g: (hash >> 8) & 255, b: (hash >> 16) & 255 };
  const image = sharp({ create: { width: 24, height: 16, channels: 3, background } });
  return format === "png" ? image.png().toBuffer() : image.jpeg().toBuffer();
}

/** `seed` keeps two cases' files apart, so neither reads the other's as a file it already has. */
export async function contentOf(name: string, seed: string): Promise<Buffer> {
  // By what the name says it is: a trailing space doesn't change what the file holds.
  const base = name.split("/").pop()!.trim().toLowerCase();
  const id = `${seed}/${name}`;
  if (base.endsWith(".gcode.3mf")) return slicedThreeMf(id);
  const ext = base.includes(".") ? base.slice(base.lastIndexOf(".")) : "";
  switch (ext) {
    case ".stl":
      return stl(id);
    case ".3mf":
      return threeMf(id);
    case ".step":
    case ".stp":
      return Buffer.concat([STEP, Buffer.from(`\n/* ${id} */\n`)]);
    case ".gcode":
      return Buffer.from(`; generated by PrusaSlicer 2.7.1\n; ${id}\n; filament used [g] = 2.10\nG28\n`);
    case ".bgcode":
      return Buffer.concat([Buffer.from("GCDE"), Buffer.from(id)]);
    case ".png":
      return picture(id, "png");
    case ".jpg":
    case ".jpeg":
      return picture(id, "jpeg");
    case ".svg":
      return Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="4" height="4"><!-- ${id} --></svg>`);
    case ".pdf":
      return Buffer.from(`%PDF-1.4\n% ${id}\n%%EOF\n`);
    case ".scad":
      return Buffer.from(`// ${id}\ncube(10);\n`);
    case ".gltf":
      return Buffer.from(
        JSON.stringify({
          asset: { version: "2.0" },
          buffers: [{ uri: "scene.bin", byteLength: 4 }],
          images: [{ uri: "textures/wood.png" }],
          extras: { id },
        }),
      );
    default:
      return Buffer.from(`${id}\n`);
  }
}

/** The zip a tree's entries make, nested zips included. */
export async function zipOf(entries: FileTree, seed: string): Promise<Buffer> {
  const out: Record<string, Buffer> = {};
  for (const [name, inner] of Object.entries(entries)) {
    out[name] = inner ? await zipOf(inner, `${seed}/${name}`) : await contentOf(name, seed);
  }
  return zip(`intake:${seed}:${Object.keys(entries).join("|")}`, out);
}

/** Every file of the tree with its bytes, by path. */
export async function filesOf(tree: FileTree, seed: string): Promise<{ path: string; bytes: Buffer }[]> {
  const out: { path: string; bytes: Buffer }[] = [];
  for (const [name, inner] of Object.entries(tree)) {
    out.push({ path: name, bytes: inner ? await zipOf(inner, `${seed}/${name}`) : await contentOf(name, seed) });
  }
  return out;
}
