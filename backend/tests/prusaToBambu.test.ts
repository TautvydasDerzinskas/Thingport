/** A PrusaSlicer 2.9 project: a two-part object on the first bed, a pin on the second, painting on the first part. */
async function prusaProject(
  options: {
    paintingVersion?: string;
    paint?: string;
    config?: string;
    modelConfig?: string;
    build?: string;
    objects?: string;
    files?: Record<string, string>;
  } = {},
): Promise<Uint8Array> {
  const zip = new JSZip();
  zip.file(
    "3D/3dmodel.model",
    `<?xml version="1.0" encoding="UTF-8"?>
<model unit="millimeter" xml:lang="en-US" xmlns="http://schemas.microsoft.com/3dmanufacturing/core/2015/02" xmlns:slic3rpe="http://schemas.slic3r.org/3mf/2017/06">
 <metadata name="slic3rpe:Version3mf">1</metadata>
 ${options.paintingVersion ? `<metadata name="slic3rpe:MmPaintingVersion">${options.paintingVersion}</metadata>` : ""}
 <metadata name="Title">Gear set</metadata>
 <metadata name="Designer">Someone</metadata>
 <metadata name="Application">PrusaSlicer-2.9.2+win64</metadata>
 <resources>
  <object id="1" type="model">
   <mesh>
    <vertices>
     <vertex x="0" y="0" z="0"/><vertex x="10" y="0" z="0"/><vertex x="0" y="10" z="0"/>
     <vertex x="20" y="0" z="0"/><vertex x="30" y="0" z="0"/><vertex x="20" y="10" z="0"/>
    </vertices>
    <triangles>
     <triangle v1="0" v2="1" v3="2" slic3rpe:mmu_segmentation="${options.paint ?? "8"}" slic3rpe:custom_supports="4"/>
     <triangle v1="3" v2="4" v3="5"/>
    </triangles>
   </mesh>
  </object>
  <object id="2" type="model">
   <mesh>
    <vertices><vertex x="0" y="0" z="0"/><vertex x="5" y="0" z="0"/><vertex x="0" y="5" z="0"/></vertices>
    <triangles><triangle v1="0" v2="1" v3="2"/></triangles>
   </mesh>
  </object>
  ${options.objects ?? ""}
 </resources>
 <build>
  ${
    options.build ??
    `<item objectid="1" transform="1 0 0 0 1 0 0 0 1 125 125 0" printable="1"/>
  <item objectid="2" transform="1 0 0 0 1 0 0 0 1 475 125 0" printable="1"/>`
  }
 </build>
</model>`,
  );
  zip.file("Metadata/Slic3r_PE.config", options.config ?? CONFIG);
  zip.file("Metadata/Slic3r_PE_model.config", options.modelConfig ?? MODEL_CONFIG);
  zip.file("Metadata/thumbnail.png", "png");
  for (const [name, text] of Object.entries(options.files ?? {})) zip.file(name, text);
  zip.file("[Content_Types].xml", '<?xml version="1.0"?><Types/>');
  zip.file("_rels/.rels", '<?xml version="1.0"?><Relationships/>');
  return zip.generateAsync({ type: "uint8array" });
}

async function copyOf(bytes: Uint8Array, plan: AdaptPlan, recipe?: PrinterRecipe) {
  const written = await adapt3mf(bytes, plan, { printer: recipe ?? null });
  const zip = await JSZip.loadAsync(await written.zip.generateAsync({ type: "uint8array" }));
  const text = async (name: string) => {
    const file = zip.file(name);
    if (!file) throw new Error(`missing ${name}`);
    return file.async("string");
  };
  return { zip, text, report: written.report() };
}

/** Each part's mesh, by the object id the root model's components name: its vertices and triangles as written. */
async function partMeshes(zip: JSZip, root: string) {
  const out: Record<string, { vertices: string[]; triangles: string[] }> = {};
  for (const m of root.matchAll(/<component p:path="\/([^"]+)" objectid="(\d+)"/g)) {
    const xml = await zip.file(m[1])!.async("string");
    const object = new RegExp(`<object id="${m[2]}"[\\s\\S]*?</object>`).exec(xml)?.[0] ?? "";
    out[m[2]] = {
      vertices: [...object.matchAll(/<vertex [^>]*\/>/g)].map((v) => v[0]),
      triangles: [...object.matchAll(/<triangle [^>]*\/>/g)].map((t) => t[0]),
    };
  }
  return out;
}

