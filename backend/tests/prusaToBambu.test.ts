describe("PrusaSlicer's colour painting", () => {
  it("is Bambu's up to the 16th filament, and each later one is written Bambu's way", () => {
    for (const code of ["4", "8", "2C", "DC", "42C1"]) expect(prusaPaintToBambu(code)).toBe(code);
    // Filament 17: PrusaSlicer's 14 with a byte of 0, Bambu's 14.
    expect(prusaPaintToBambu("00EC")).toBe("EC");
    // 18 and 33: Bambu adds 15 for each 15 before the last nibble.
    expect(prusaPaintToBambu("01EC")).toBe("0FC");
    expect(prusaPaintToBambu("10EC")).toBe("0FFC");
    // A split triangle: the 17th filament on one half, the first on the other.
    expect(prusaPaintToBambu("400EC1")).toBe("4EC1");
  });
});

